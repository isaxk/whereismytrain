	<h3>Train location system</h3>
	<p>
		<b>Note</b> that the train location system is purely an indication of a train's progress along its
		route, and not actual location data. Therefore, the system must not be used for safety-critical purposes.
	</p>
	<p>Train locations are <span class="font-bold">estimates</span> calculated based on 2 factors</p>
	<ul>
		<li>The train's last reported departure from a timing point (TIPLOC)</li>
		<li>An estimation of the train's progress to the next TIPLOC</li>
	</ul>
